callbacks.Register("CreateMove", function(cmd)
    if not aimbot_enable:GetValue() then return end
    
    local lp = entities.GetLocalPawn()
    if not lp or not lp:IsAlive() then return end
    
    local target = getBestTarget()
    if not target then return end
    
    local hitbox_index = getActiveHitboxIndex()
    local target_pos = target:GetHitboxPosition(hitbox_index)
    if not target_pos or target_pos:Length() < 10 then return end
    
    local eye_pos = lp:GetAbsOrigin() + Vector3(0, 0, 64)
    
    local delta = target_pos - eye_pos
    local target_angles = delta:Angles()
    local current_view = engine.GetViewAngles()
    
    local delta_angles = target_angles - current_view
    delta_angles:Normalize()
    
    local smooth_val = math.max(1, aimbot_smooth:GetValue())
    local new_angles = current_view + (delta_angles / smooth_val)
    new_angles:Normalize()
    
    new_angles.x = math.max(-89, math.min(89, new_angles.x))
    new_angles.z = 0
    engine.SetViewAngles(new_angles)
end)

