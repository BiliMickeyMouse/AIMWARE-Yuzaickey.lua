local function drawHitlogs()
    if not hitlogs_enable:GetValue() then
        hitlogs_hits = {}
        return
    end

    local time = common.Time()
    local font_size = HL_FONT_SIZE
    local offset_y = hitlogs_offset_y:GetValue()

    if hitlogs_font == nil or hitlogs_cached_font_size ~= font_size then
        hitlogs_font = draw.CreateFont("Arial", font_size, 900)
        hitlogs_font_shadow = draw.CreateFont("Arial", font_size, 900, true)
        hitlogs_cached_font_size = font_size
    end

    local center_x = screen_width / 2
    local start_y = screen_height / 2 + offset_y

    local animation_sum = 0
    local to_remove = 0

    for hit = 1, #hitlogs_hits do
        if hitlogs_hits[hit] then
            local segments = hitlogs_hits[hit][1]
            local duration = hitlogs_hits[hit][2] - time

            if duration >= 0 then
                local animation_scaler = 1
                local FULL_DURATION = 5
                local ANIMATION_TIME = 0.5

                if duration > FULL_DURATION - ANIMATION_TIME then
                    animation_scaler = (FULL_DURATION - duration) * (1 / ANIMATION_TIME)
                elseif duration < ANIMATION_TIME then
                    animation_scaler = duration * (1 / ANIMATION_TIME)
                end

                local BETWEEN_HITS_DISTANCE = 25
                animation_sum = animation_sum + BETWEEN_HITS_DISTANCE * animation_scaler

                local x_pos = center_x
                local y_pos = start_y + animation_sum - BETWEEN_HITS_DISTANCE

                -- 计算总文字宽度
                draw.SetFont(hitlogs_font_shadow)
                local total_w = 0
                for _, seg in ipairs(segments) do
                    total_w = total_w + draw.GetTextSize(seg[2])
                end

                local PAD = 6
                local bg_x1 = x_pos - total_w / 2 - PAD
                local bg_y1 = y_pos - PAD
                local bg_x2 = x_pos + total_w / 2 + PAD
                local bg_y2 = y_pos + font_size + PAD

                -- 背景颜色根据模式（不透明度由用户控制）
                local theme = HL_THEMES[hitlogs_theme:GetValue()]
                local user_alpha = math.floor(hitlogs_bg_alpha:GetValue() / 100 * 255)
                draw.Color(theme.bg_r, theme.bg_g, theme.bg_b, animation_scaler * user_alpha)
                draw.RoundedRectFill(bg_x1, bg_y1, bg_x2, bg_y2, 5)

                -- 逐段绘制阴影 + 彩色文字
                local cx = bg_x1 + PAD
                for _, seg in ipairs(segments) do
                    local cr, cg, cb = seg[1][1], seg[1][2], seg[1][3]
                    local stext = seg[2]

                    -- 阴影（浅色模式无阴影）
                    if hitlogs_theme:GetValue() == 0 then
                        draw.Color(0, 0, 0, animation_scaler * 255)
                        draw.SetFont(hitlogs_font_shadow)
                        draw.Text(cx, y_pos, stext)
                    end

                    -- 彩色文字
                    draw.Color(cr, cg, cb, animation_scaler * 255)
                    draw.SetFont(hitlogs_font)
                    draw.Text(cx, y_pos, stext)

                    cx = cx + draw.GetTextSize(stext)
                end
            else
                to_remove = to_remove + 1
            end
        end
    end

    if to_remove > 0 then
        local cleared_hits = {}
        for i = to_remove + 1, #hitlogs_hits do
            cleared_hits[#cleared_hits + 1] = hitlogs_hits[i]
        end
        hitlogs_hits = cleared_hits
    end

    local local_entity = entities.GetLocalPawn()
    if not local_entity then
        hitlogs_hits = {}
    end
end

-- PreMove回调 (SpinBot)
callbacks.Register("PreMove", function(cmd)
    if not spin_enable:GetValue() then return end
    
    local speed = spin_speed:GetValue() * 0.5
    current_yaw = (current_yaw + speed) % 360
    local final_yaw = current_yaw
    if final_yaw > 180 then final_yaw = final_yaw - 360 end
    
    -- 根据俯仰模式设置pitch
    local mode = spin_mode:GetValue()
    local pitch = 0
    
    if mode == 0 then
        -- 低头
        pitch = 89
    elseif mode == 1 then
        -- 平视
        pitch = 0
    elseif mode == 2 then
        -- 抬头
        pitch = -89
    elseif mode == 3 then
        -- 抖动
        jitter_seed = jitter_seed + 1
        pitch = (math.sin(globals.RealTime() * 10 + jitter_seed) * 89)
    end
    
    local va = cmd:GetViewAngles()
    va.y = final_yaw
    va.x = pitch
    cmd:SetViewAngles(va)
end)

