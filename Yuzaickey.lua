            local smooth = gui.GetValue("lbot.weapon.aim." .. weapon_group .. ".smooth")
            local delay = real_distance * (smooth + 1)
            gui.SetValue("lbot.weapon.target." .. weapon_group .. ".fsd", delay)
        end
    end)
end

