local function drawIndicators()
    if not spin_enable:GetValue() then return end

    local center_x = screen_width / 2
    local start_y = screen_height / 2 + 8
    local font_size = 12
    local font_name = "Arial"

    if indicator_cached_font == nil then
        indicator_cached_font = draw.CreateFont(font_name, font_size, 700)
        indicator_cached_shadow = draw.CreateFont(font_name, font_size, 700, false)
    end

    if indicator_cached_font then
        draw.SetFont(indicator_cached_font)
    end

    -- 收集所有要显示的文本段
    local segments = {}
    if indicator_show_spin:GetValue() then
        local sr, sg, sb, sa = indicator_color_spin:GetValue()
        segments[#segments + 1] = {"Spinning", sr, sg, sb, sa}
    end
    if indicator_show_speed:GetValue() then
        local sr, sg, sb, sa = indicator_color_speed:GetValue()
        segments[#segments + 1] = {"Speed - " .. spin_speed:GetValue(), sr, sg, sb, sa}
    end
    if indicator_show_mode:GetValue() then
        local mode = spin_mode:GetValue()
        local mode_name = spin_mode_names[mode + 1] or "Down"
        local mr, mg, mb, ma = indicator_color_mode:GetValue()
        segments[#segments + 1] = {"Mode - " .. mode_name, mr, mg, mb, ma}
    end

    -- 同一行内联显示，用 | 分隔
    if #segments > 0 then
        local SEP = " | "
        local total_w = 0
        for _, seg in ipairs(segments) do
            total_w = total_w + draw.GetTextSize(seg[1]) + draw.GetTextSize(SEP)
        end
        total_w = total_w - draw.GetTextSize(SEP)  -- 去掉末尾多余分隔符

        local cx = center_x - total_w / 2
        local y = start_y

        for i, seg in ipairs(segments) do
            -- 阴影
            if indicator_cached_shadow then
                draw.SetFont(indicator_cached_shadow)
                draw.Color(0, 0, 0, math.floor(seg[5] * 0.6))
                draw.Text(cx + 1, y + 1, seg[1])
            end
            -- 主文字
            draw.SetFont(indicator_cached_font)
            draw.Color(seg[2], seg[3], seg[4], seg[5])
            draw.Text(cx, y, seg[1])
            cx = cx + draw.GetTextSize(seg[1]) + draw.GetTextSize(SEP)

            -- 分隔符
            if i < #segments then
                if indicator_cached_shadow then
                    draw.SetFont(indicator_cached_shadow)
                    draw.Color(0, 0, 0, 150)
                    draw.Text(cx - draw.GetTextSize(SEP) + 1, y + 1, SEP)
                end
                draw.SetFont(indicator_cached_font)
                draw.Color(150, 150, 150, 200)
                draw.Text(cx - draw.GetTextSize(SEP), y, SEP)
            end
        end
    end
end

