-- Skeet2: 经典SK样式 — 透明外框 + 内边框线 + HSV彩虹流动边框
watermark_styles[1] = {
    decor = function(x1, y1, x2, y2)
        local outerPad = 4
        local ox1, oy1, ox2, oy2 = x1 - outerPad, y1 - outerPad, x2 + outerPad, y2 + outerPad

        -- 外层透明框
        draw.Color(40, 40, 40, 220)
        draw.FilledRect(ox1, oy1, ox2, oy2)
        drawRectOutline(ox1, oy1, ox2 - ox1, oy2 - oy1, 200, 200, 200, 40)

        -- 内层边框线
        drawRectOutline(x1, y1, x2 - x1, y2 - y1, 200, 200, 200, 40)

        -- HSV彩虹流动边框（沿外层框）
        local t     = globals.RealTime() * 0.3
        local ow    = ox2 - ox1
        local oh    = oy2 - oy1
        local total = 2 * (ow + oh)
        for px = ox1, ox2 - 1 do
            local prog = (px - ox1) / total
            local rr, rg2, rb = sk_hsv2rgb(t + prog, 1, 1)
            draw.Color(rr, rg2, rb, 255)
            draw.FilledRect(px, oy1, px + 1, oy1 + 1)
        end
        for py = oy1, oy2 - 1 do
            local prog = (ow + py - oy1) / total
            local rr, rg2, rb = sk_hsv2rgb(t + prog, 1, 1)
            draw.Color(rr, rg2, rb, 255)
            draw.FilledRect(ox2 - 1, py, ox2, py + 1)
        end
        for px = ox2 - 1, ox1, -1 do
            local prog = (ow + oh + (ox2 - 1 - px)) / total
            local rr, rg2, rb = sk_hsv2rgb(t + prog, 1, 1)
            draw.Color(rr, rg2, rb, 255)
            draw.FilledRect(px, oy2 - 1, px + 1, oy2)
        end
        for py = oy2 - 1, oy1, -1 do
            local prog = (ow * 2 + oh + (oy2 - 1 - py)) / total
            local rr, rg2, rb = sk_hsv2rgb(t + prog, 1, 1)
            draw.Color(rr, rg2, rb, 255)
            draw.FilledRect(ox1, py, ox1 + 1, py + 1)
        end
    end,
}

