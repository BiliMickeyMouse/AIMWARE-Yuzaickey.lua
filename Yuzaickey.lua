-- Aimbot Hitbox 映射表
local hitbox_map = {0, 6, 5, 3, 17, 16, 10, 9}
local hitbox_names = {"HEAD", "NECK", "CHEST", "STOMACH", "LEFT ARM", "RIGHT ARM", "LEFT LEG", "RIGHT LEG"}

local screen_width, screen_height = draw.GetScreenSize()

-- ==================== 全局辅助函数 ====================
-- draw.GetTextSize 返回两个值 (width, height)，必须提取宽度
local function textW(str)
    local w, _ = draw.GetTextSize(str)
    return w or 0
end

-- 获取当前选择的 Aimbot Hitbox 索引
local function getActiveHitboxIndex()
    return hitbox_map[aimbot_hitbox:GetValue() + 1] or 0
end

-- 获取当前选择的 Aimbot Hitbox 名称
local function getActiveHitboxName()
    return hitbox_names[aimbot_hitbox:GetValue() + 1] or "HEAD"
end

-- 获取最佳目标
local function getBestTarget()
    local local_pawn = entities.GetLocalPawn()
    if not local_pawn or not local_pawn:IsAlive() then return nil end

    local cx, cy = screen_width / 2, screen_height / 2
    local best_target = nil
    local best_dist = aimbot_fov:GetValue()
    
    local hitbox_index = getActiveHitboxIndex()
    local players = entities.FindByClass("C_CSPlayerPawn")
    if not players then return nil end

    local target_mode = aimbot_target:GetValue() -- 0=敌人, 1=队友, 2=全部

    for _, entity in pairs(players) do
        -- 排除自己
        if entity:IsPlayer() and 
           entity:IsAlive() and 
           entity:GetHealth() > 0 and 
           entity:GetIndex() ~= local_pawn:GetIndex() then
            
            local is_enemy = entity:GetTeamNumber() ~= local_pawn:GetTeamNumber()
            local is_teammate = not is_enemy
            
            -- 根据目标模式筛选
            local valid_target = false
            if target_mode == 0 then
                valid_target = is_enemy
            elseif target_mode == 1 then
                valid_target = is_teammate
            else -- target_mode == 2, 全部
                valid_target = true
            end
            
            if valid_target then
                local target_pos = entity:GetHitboxPosition(hitbox_index)
                if target_pos and target_pos:Length() > 10 then
                    local sx, sy = client.WorldToScreen(target_pos)
                    if sx and sy then
                        local d = math.sqrt((sx - cx)^2 + (sy - cy)^2)
                        if d < best_dist then
                            best_dist = d
                            best_target = entity
                        end
                    end
                end
            end
        end
    end
    return best_target
end

-- 绘制 FOV 范围
local function drawFovCircle()
    local local_entity = entities.GetLocalPawn()
    if not local_entity or not local_entity:IsAlive() then return end
    
    -- 启用绘制
    if aimbot_fov_draw_enable:GetValue() then
        local draw_mode = aimbot_fov_draw_mode:GetValue() -- 0=瞄准时绘制, 1=一直绘制
        if draw_mode == 0 and not aimbot_enable:GetValue() then
            return
        end

        local fov = aimbot_fov:GetValue()
        local radius = fov * 1.5
        
        local r, g, b, a = aimbot_fov_draw_color:GetValue()
        draw.Color(r, g, b, a)
        
        local thickness = aimbot_fov_draw_thickness:GetValue()
        for i = 0, thickness - 1 do
            draw.OutlinedCircle(screen_width / 2, screen_height / 2, radius + i)
        end
    end
end

local aiminfo_cached_font = nil
local aiminfo_cached_shadow = nil
local function drawAimInfo()
    if not aimbot_indicator_enable:GetValue() then return end
    if not aimbot_enable:GetValue() then return end

    local target = getBestTarget()
    if not target then return end

    local hitbox_name = getActiveHitboxName()

    local name = "Target"
    local ok = pcall(function() name = target:GetName() end)
    if not ok or not name or name == "" then
        pcall(function()
            name = client.GetPlayerNameByIndex(target:GetIndex())
        end)
    end
    if not name or name == "" then
        name = tostring(target:GetIndex() or "Target")
    end

    local text_prefix = "Aiming "
    local text_mid = name .. "'s "
    local text_hitbox = hitbox_name
    local font_size = 12
    if aiminfo_cached_font == nil then
        aiminfo_cached_font = draw.CreateFont("Arial", font_size, 700)
        aiminfo_cached_shadow = draw.CreateFont("Arial", font_size, 700, false)
    end

    local tw = draw.GetTextSize(text_prefix) + draw.GetTextSize(text_mid) + draw.GetTextSize(text_hitbox)
    local cross_x = screen_width / 2
    local cross_y = screen_height / 2

    local pos = aimbot_indicator_pos:GetValue() -- 0=Down,1=Up,2=Left,3=Right
    local gap = 28
    local x, y
    if pos == 1 then
        x = cross_x - (tw / 2)
        y = cross_y - gap - font_size
    elseif pos == 2 then
        x = cross_x - gap - tw
        y = cross_y - (font_size / 2)
    elseif pos == 3 then
        x = cross_x + gap
        y = cross_y - (font_size / 2)
    else
        x = cross_x - (tw / 2)
        y = cross_y + gap
    end

    local function drawSegmentedText(dx, dy, shadow)
        local cx = x + dx
        local cy = y + dy

        if shadow then
            draw.SetFont(aiminfo_cached_shadow)
        else
            draw.SetFont(aiminfo_cached_font)
        end

        if shadow then
            draw.Color(0, 0, 0, 200)
        else
            draw.Color(255, 60, 60, 255) -- Aiming: red
        end
        draw.Text(cx, cy, text_prefix)
        cx = cx + draw.GetTextSize(text_prefix)

        if shadow then
            draw.Color(0, 0, 0, 200)
        else
            draw.Color(255, 255, 255, 255) -- name + 's: white
        end
        draw.Text(cx, cy, text_mid)
        cx = cx + draw.GetTextSize(text_mid)

        if shadow then
            draw.Color(0, 0, 0, 200)
        else
            draw.Color(60, 255, 60, 255) -- hitbox: green
        end
        draw.Text(cx, cy, text_hitbox)
    end

    drawSegmentedText(1, 1, true)
    drawSegmentedText(0, 0, false)
end


