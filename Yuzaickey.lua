-- 统一 FireGameEvent 回调 (击杀/死亡喊话 + 对局重置)
callbacks.Register("FireGameEvent", function(event)
    if not event then return end
    local event_name = event:GetName()

    -- ========== 击杀/死亡喊话 ==========
    if event_name == "player_death" then
        local local_player = entities.GetLocalPlayer()
        if not local_player then return end

        local my_ctrl_idx = getMyControllerIndex(local_player)
        if not my_ctrl_idx then return end

        local attackerID = event:GetInt("attacker")
        local victimID = event:GetInt("userid")

        if kill_chat_enable:GetValue() then
            if (attackerID + 1) == my_ctrl_idx and attackerID ~= victimID then
                local current_time = globals.RealTime()
                if current_time - last_kill_time >= kill_cooldown then
                    local pool = kill_content_pools[kill_chat_select:GetValue() + 1]
                    local msg = getRandomMessage(pool)
                    if msg then
                        client.ChatSay(msg)
                        last_kill_time = current_time
                    end
                end
            end
        end

        if death_chat_enable:GetValue() then
            if (victimID + 1) == my_ctrl_idx and attackerID ~= victimID then
                local current_time = globals.RealTime()
                if current_time - last_death_time >= death_cooldown then
                    local pool = death_content_pools[death_chat_select:GetValue() + 1]
                    local msg = getRandomMessage(pool)
                    if msg then
                        client.ChatSay(msg)
                        last_death_time = current_time
                    end
                end
            end
        end
    end

    -- ========== 对局重置 ==========
    if event_name == "cs_win_panel_match" or event_name == "round_start" or event_name == "game_newatermarkap" then
        last_kill_time = 0
        last_death_time = 0
        spam_last_tick = 0
        spam_index = 1
    end
end)

